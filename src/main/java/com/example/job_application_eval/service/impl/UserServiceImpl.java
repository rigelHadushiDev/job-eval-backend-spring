package com.example.job_application_eval.service.impl;

import com.example.job_application_eval.dtos.ChangePasswordDto;
import com.example.job_application_eval.dtos.UserDto;
import com.example.job_application_eval.entities.UserEntity;
import com.example.job_application_eval.entities.enums.Role;
import com.example.job_application_eval.mappers.Mapper;
import com.example.job_application_eval.repository.UserRepository;
import com.example.job_application_eval.responses.GeneralSuccessfulResp;
import com.example.job_application_eval.service.AuthenticationService;
import com.example.job_application_eval.service.UserService;
import jakarta.transaction.Transactional;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.http.HttpStatus;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Optional;
import java.util.concurrent.atomic.AtomicBoolean;

@Service
@RequiredArgsConstructor
public class UserServiceImpl implements UserService {

    private final UserRepository userRepository;
    private final PasswordEncoder passwordEncoder;
    private final AuthenticationService authService;
    private final Mapper<UserEntity, UserDto> userMapper;

    @Override
    public Page<UserDto> allUsers(Pageable pageable) {
        Page<UserEntity> entities = userRepository.findAll(pageable);
        return entities.map(userMapper::mapTo);
    }

    @Override
    public Page<UserDto> findUsersByRoles(List<Role> roles, Pageable pageable) {
        Page<UserEntity> entities = userRepository.findByRoleIn(roles, pageable);
        return entities.map(userMapper::mapTo);
    }

    @Override
    public UserDto getCurrentUser() {
        String username = SecurityContextHolder.getContext().getAuthentication().getName();
        UserEntity currentUser =  userRepository.findByUsername(username).orElseThrow(() ->
                new ResponseStatusException(HttpStatus.NOT_FOUND, "userNotFound"));
        return userMapper.mapTo(currentUser);
    }

    @Override
    public GeneralSuccessfulResp changeUserPassword(ChangePasswordDto changePasswordDto) {
        UserDto userDto = getCurrentUser();
        UserEntity user = userMapper.mapFrom(userDto);
        user.setPassword(passwordEncoder.encode(changePasswordDto.getNewPassword()));
        user.setPasswordChanged(true);
        user.setAutoGeneratedPasswordExpiresAt(null);
        userRepository.save(user);
        return new GeneralSuccessfulResp("successfullyChangedPassword");
    }


    @Override
    public UserDto deleteYourUserAccount() {
        UserDto currentUserDto = getCurrentUser();
        UserEntity currentUser = userMapper.mapFrom(currentUserDto);
        userRepository.delete(currentUser);
        return currentUserDto;
    }

    @Override
    public UserDto deleteUser(Long userId) {
        UserEntity currentUser = userRepository.findById(userId)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "userNotFound"));

        userRepository.delete(currentUser);
        return userMapper.mapTo(currentUser);
    }

    @Override
    public UserDto editCurrUserData(UserDto patch) {

        String username = SecurityContextHolder.getContext().getAuthentication().getName();
        UserEntity currentUser = userRepository.findByUsername(username)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "userNotFound"));

        boolean fullNameChanged = false;

        if (patch.getFirstname() != null && !patch.getFirstname().equals(currentUser.getFirstname())) {
            currentUser.setFirstname(patch.getFirstname());
            fullNameChanged = true;
        }
        if (patch.getLastname() != null && !patch.getLastname().equals(currentUser.getLastname())) {
            currentUser.setLastname(patch.getLastname());
            fullNameChanged = true;
        }
        if (fullNameChanged) {
            String first = Optional.ofNullable(currentUser.getFirstname()).orElse("");
            String last  = Optional.ofNullable(currentUser.getLastname()).orElse("");
            currentUser.setFullName((first + " " + last).trim());
        }

        if (patch.getGender() != null) {
            currentUser.setGender(patch.getGender());
        }
        if (patch.getBirthdate() != null) {
            currentUser.setBirthdate(patch.getBirthdate());
        }
        if (patch.getMobileNumber() != null) {
            currentUser.setMobileNumber(patch.getMobileNumber());
        }


        if (patch.getUsername() != null && !patch.getUsername().equals(currentUser.getUsername())) {
            List<UserEntity> same = userRepository.findAllByUsername(patch.getUsername());
            boolean takenByAnother = same.stream()
                    .anyMatch(u -> !u.getUserId().equals(currentUser.getUserId()));
            if (takenByAnother) {
                throw new ResponseStatusException(HttpStatus.CONFLICT, "usernameTaken");
            }
            currentUser.setUsername(patch.getUsername());
        }


        UserEntity saved = userRepository.save(currentUser);
        return userMapper.mapTo(saved);
    }

    @Override
    public Page<UserDto> searchUsersByFullName(String fullName, Pageable pageable) {
        Page<UserEntity> entities = userRepository.findByFullNameContainingIgnoreCase(fullName, pageable);
        return entities.map(userMapper::mapTo);
    }


    @Override
    public UserDto save(UserDto userDto) {

        UserEntity userEntity = userMapper.mapFrom(userDto);

        Optional<UserEntity> existingUserName = userRepository.findByUsername(userEntity.getUsername());
        Optional<UserEntity> existingEmail = userRepository.findByEmail(userEntity.getEmail());

        if (existingUserName.isPresent()) {
            throw new ResponseStatusException(
                    HttpStatus.CONFLICT,
                    "usernameTaken"
            );
        }

        if (existingEmail.isPresent()) {
            throw new ResponseStatusException(
                    HttpStatus.CONFLICT,
                    "emailTaken"
            );
        }
        String rawTemporaryPassword = authService.generateTemporaryPassword();
        String hashedTemporaryPassword = passwordEncoder.encode(rawTemporaryPassword);

        UserEntity user = UserEntity.builder()
                .email(userEntity.getEmail())
                .username(userEntity.getUsername())
                .password(hashedTemporaryPassword)
                .lastname(userEntity.getLastname())
                .firstname(userEntity.getFirstname())
                .fullName(userEntity.getFirstname() + " " + userEntity.getLastname())
                .role(userEntity.getRole())
                .autoGeneratedPasswordExpiresAt(LocalDateTime.now().plusHours(2))
                .passwordChanged(false)
                .build();

        authService.sendVerificationEmail(user, rawTemporaryPassword);
        UserEntity savedUser =  userRepository.save(user);
        return userMapper.mapTo(savedUser);
    }

    @Override
    public UserDto getUserByUserName(String username) {
        UserEntity entity = userRepository.findByUsername(username)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "userNotFound"));
        return userMapper.mapTo(entity);
    }
}
