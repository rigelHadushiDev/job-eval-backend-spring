package com.example.job_application_eval.controller;

import com.example.job_application_eval.dtos.LoginUserDto;
import com.example.job_application_eval.dtos.UserDto;
import com.example.job_application_eval.entities.UserEntity;
import com.example.job_application_eval.mappers.Mapper;
import com.example.job_application_eval.responses.LogInResponse;
import com.example.job_application_eval.service.AuthenticationService;
import com.example.job_application_eval.validation.OnSignUpUser;
import jakarta.servlet.http.Cookie;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpHeaders;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseCookie;
import org.springframework.http.ResponseEntity;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;

@RequestMapping("/auth")
@RestController
@RequiredArgsConstructor
public class AuthenticationController {

    private final AuthenticationService authenticationService;
    private final Mapper<UserEntity, UserDto> userMapper;

    @PostMapping("/signup")
    public ResponseEntity<?> signup(@Validated(OnSignUpUser.class) @RequestBody UserDto userDto) {
        UserEntity userEntity = userMapper.mapFrom(userDto);
        UserEntity registeredUser = authenticationService.signup(userEntity);
        return ResponseEntity.ok(userMapper.mapTo(registeredUser));
    }


    @PostMapping("/login")
    public ResponseEntity<LogInResponse> authenticate(
            @Valid @RequestBody LoginUserDto loginUserDto
    ) {
        LogInResponse result = authenticationService.authenticate(loginUserDto);

        // DEV MODE COOKIE (http://localhost)
        ResponseCookie cookie = ResponseCookie.from("refreshToken", result.getRefreshToken())
                .httpOnly(true)
                .secure(false)          // ❗ false in dev because you're not on https
                .sameSite("Lax")         // ❗ "None" requires secure(true); so use Lax in dev
                .path("/auth/refresh")   // cookie will be sent ONLY to /auth/refresh
                .maxAge(result.getExpiresIn()) // <-- seconds. make sure it's seconds.
                .build();

        // what we send back to frontend in JSON (no refresh token)
        LogInResponse body = new LogInResponse(
                result.getUserId(),
                result.getAccessToken(),
                null,
                result.getExpiresIn(),
                result.getRole(),
                result.isPasswordChanged()
        );

        return ResponseEntity.ok()
                .header(HttpHeaders.SET_COOKIE, cookie.toString())
                .body(body);
    }

    @PostMapping("/refresh")
    public ResponseEntity<LogInResponse> refreshAccessToken(
            @CookieValue(value = "refreshToken", required = false) String refreshToken
    ) {
        if (refreshToken == null) {
            throw new ResponseStatusException(HttpStatus.UNAUTHORIZED, "noRefreshToken");
        }

        LogInResponse result = authenticationService.refreshAccessToken(refreshToken);
        ResponseCookie cookie = ResponseCookie.from("refreshToken", result.getRefreshToken())
                .httpOnly(true)
                .secure(false)
                .sameSite("Lax")
                .path("/auth/refresh")
                .maxAge(result.getExpiresIn())
                .build();

        LogInResponse body = new LogInResponse(
                result.getUserId(),
                result.getAccessToken(),
                null,
                result.getExpiresIn(),
                result.getRole(),
                result.isPasswordChanged()
        );

        return ResponseEntity.ok()
                .header(HttpHeaders.SET_COOKIE, cookie.toString())
                .body(body);
    }


    @PostMapping("/resend")
    public ResponseEntity<?> resendAutoGeneratedPassword(@RequestParam String username) {
        authenticationService.resendAutoGeneratedPassword(username);
        return ResponseEntity.ok("Temporary password sent");
    }
}
